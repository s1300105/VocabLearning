def substitution_tip(phone_base: str, heard: Optional[str]) -> Optional[str]:
    if heard is None:
        return None
    for expected, heard_set, tip in SUBSTITUTION_TIPS:
        if expected == phone_base and heard in heard_set:
            return tip
    return None


def describe_issue(issue: str, expected_display: str, heard: Optional[str] = None,
                   phone_base: str = '') -> str:
    """問題の種類ごとに、学習者向けの説明文を作る"""
    heard_display = display_token(heard)
    if issue == 'missing':
        return f'/{expected_display}/ がほとんど聞こえません。はっきり発音しましょう。'
    if issue == 'inserted_vowel':
        return (f'/{expected_display}/ のあとに母音（{heard_display}）が入っています。'
                '日本語のように母音を付けず、子音だけで止めましょう。')
    if issue == 'substitution' and heard_display:
        message = f'/{expected_display}/ が /{heard_display}/ のように聞こえます。'
        tip = substitution_tip(phone_base, heard)
        return f'{message}{tip}' if tip else message
    return f'/{expected_display}/ の発音が不明瞭です。'
